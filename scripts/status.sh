#!/bin/bash
set -e

# Display current system status for IoT project
echo "📊 CURRENT SYSTEM STATUS"
echo "========================="
echo ""
echo "🔍 PART 1 (p1): Vagrant + K3s"
(cd p1 && vagrant status 2>/dev/null) || echo "  p1 not initialized"
echo ""
echo "🔍 PART 2 (p2): Vagrant + Apps"
(cd p2 && vagrant status 2>/dev/null) || echo "  p2 not initialized"
echo ""
echo "🔍 PART 3 (p3): K3d + ArgoCD"
k3d cluster list 2>/dev/null | grep iot-cluster || echo "  p3 not initialized"
echo "  ArgoCD: http://42.fr:30080"
echo "  🔑 ArgoCD credentials:"
echo "    - User: admin"
echo -n "    - Password: "
kubectl -n argocd get secret argocd-initial-admin-secret -o jsonpath='{.data.password}' 2>/dev/null | base64 -d || echo "(not available)"
echo ""
echo "🔍 BONUS: K3d + GitLab"
kubectl get pods -n gitlab 2>/dev/null | grep gitlab || echo "  Bonus not initialized"
echo "  GitLab: http://42.fr:30081"
echo "  Application: http://42.fr:30888"
echo "  🔑 GitLab credentials:"
echo "    - User: root"
echo -n "    - Password: "
kubectl get secret gitlab-gitlab-initial-root-password -n gitlab -o jsonpath='{.data.password}' 2>/dev/null | base64 -d || echo "(not available)"
echo ""
echo "🔍 VAGRANT GLOBAL:"
vagrant global-status 2>/dev/null || echo "  No active Vagrant VM"
echo ""
echo "🔍 K3D CLUSTERS:"
k3d cluster list 2>/dev/null || echo "  No K3d cluster"
echo ""
echo "🔍 DOCKER CONTAINERS:"
docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}" 2>/dev/null || echo "  Docker not available"
echo ""
echo "🔍 DOCKER IMAGES:"
docker images --format "table {{.Repository}}\t{{.Tag}}\t{{.Size}}" 2>/dev/null | head -10 || echo "  Docker not available"
echo ""
echo "🔍 ACTIVE PORTS (30080-30888):"
netstat -tuln 2>/dev/null | grep -E ":(3008[0-8]|30888)" || echo "  No active project port"
echo ""
echo "🔍 USED DISK SPACE:"
du -sh ~/.vagrant.d/ 2>/dev/null | sed 's/^/  Vagrant: /' || echo "  Vagrant: 0"
docker system df 2>/dev/null | tail -n +2 | sed 's/^/  /' || echo "  Docker: not available"
echo ""
